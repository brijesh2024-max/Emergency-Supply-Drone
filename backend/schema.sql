CREATE TABLE IF NOT EXISTS users (
 username TEXT PRIMARY KEY, role TEXT NOT NULL, salt TEXT NOT NULL, digest TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 digest TEXT PRIMARY KEY, username TEXT NOT NULL REFERENCES users(username), expires REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS drones (
 id TEXT PRIMARY KEY, model TEXT NOT NULL, capacity REAL NOT NULL, battery REAL NOT NULL,
 lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL, altitude REAL NOT NULL DEFAULT 0,
 link INTEGER NOT NULL DEFAULT 1, status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS inventory (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, mass REAL NOT NULL, available INTEGER NOT NULL CHECK(available >= 0)
);
CREATE TABLE IF NOT EXISTS detections (
 id TEXT PRIMARY KEY, sector TEXT NOT NULL, lat DOUBLE PRECISION NOT NULL, lon DOUBLE PRECISION NOT NULL,
 source TEXT NOT NULL, confidence REAL, status TEXT NOT NULL, priority TEXT NOT NULL,
 observed TEXT NOT NULL, reviewed_by TEXT, evidence TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS missions (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, kind TEXT NOT NULL, drone TEXT NOT NULL REFERENCES drones(id),
 zone TEXT NOT NULL, route TEXT NOT NULL, progress REAL NOT NULL DEFAULT 0, status TEXT NOT NULL,
 item TEXT REFERENCES inventory(id), qty INTEGER NOT NULL, candidate TEXT REFERENCES detections(id),
 reserved INTEGER NOT NULL DEFAULT 0, created_by TEXT NOT NULL, approved_by TEXT, created TEXT NOT NULL,
 patrol INTEGER NOT NULL DEFAULT 0, return_reason TEXT
);
CREATE TABLE IF NOT EXISTS events (
 id TEXT PRIMARY KEY, time TEXT NOT NULL, kind TEXT NOT NULL, message TEXT NOT NULL, actor TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS events_time ON events(time);
CREATE TABLE IF NOT EXISTS settings (name TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS alerts (
 id TEXT PRIMARY KEY, severity TEXT NOT NULL, message TEXT NOT NULL, detail TEXT NOT NULL, acknowledged_by TEXT
);
